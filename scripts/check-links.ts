#!/usr/bin/env bun
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs'
import { dirname, extname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { createMarkdownRenderer } from 'vitepress'
import type { MarkdownRenderer } from 'vitepress'
import type Token from 'markdown-it/lib/token.mjs'
import { markdownOptions } from '../docs/.vitepress/markdown/index.ts'

interface Link { href: string; line: number }
export interface MarkdownLinks { anchors: Set<string>; links: Link[] }
export interface LinkCheckResult { checked: number; errors: string[] }

/** Use the site's actual token stream: no copied slugifier or link regex. */
export function analyzeMarkdown(md: MarkdownRenderer, text: string, relativePath: string): MarkdownLinks {
  const anchors = new Set<string>()
  const links: Link[] = []
  function visit(tokens: Token[], parentLine = 1): void {
    for (const token of tokens) {
      const line = token.map ? token.map[0] + 1 : parentLine
      const id = token.attrGet('id')
      if (id) anchors.add(id)
      const href = token.type === 'link_open' ? token.attrGet('href') : token.type === 'image' ? token.attrGet('src') : null
      if (href && !token.attrGet('class')?.split(/\s+/).includes('header-anchor')) links.push({ href, line })
      // Static HTML IDs are also valid destinations. Do not inspect code tokens
      // or HTML comments, which can contain examples rather than real anchors.
      if (token.type === 'html_inline' || token.type === 'html_block') {
        const html = token.content.replace(/<!--[\s\S]*?-->/g, '')
        for (const match of html.matchAll(/\bid\s*=\s*(?:"([^"]+)"|'([^']+)')/g)) anchors.add(match[1] ?? match[2])
      }
      if (token.children) visit(token.children, line)
    }
  }
  visit(md.parse(text, { relativePath }))
  return { anchors, links }
}

const inside = (root: string, file: string): boolean => {
  const path = relative(root, file)
  return path !== '..' && !path.startsWith(`..${sep}`) && !isAbsolute(path)
}
const isFile = (file: string): boolean => existsSync(file) && statSync(file).isFile()

/** Check source routes/public assets; no built site, network or Python needed. */
export async function checkLinks(docs: string, base = '/'): Promise<LinkCheckResult> {
  docs = resolve(docs)
  const md = await createMarkdownRenderer(docs, markdownOptions, base)
  const analyses = new Map<string, MarkdownLinks>()
  const analyzeFile = (file: string) => {
    let analysis = analyses.get(file)
    if (!analysis) {
      analysis = analyzeMarkdown(md, readFileSync(file, 'utf8'), relative(docs, file).split(sep).join('/'))
      analyses.set(file, analysis)
    }
    return analysis
  }
  function findTarget(path: string, source: string): string | undefined {
    // Pagefind/cleanUrls and source .md links must resolve to the same page.
    if (base !== '/' && path.startsWith(base)) path = '/' + path.slice(base.length)
    const absolute = path.startsWith('/')
    const stem = resolve(absolute ? docs : dirname(source), absolute ? path.slice(1) : path)
    if (!inside(docs, stem)) return undefined
    const clean = stem.replace(/\.html$/, '.md')
    for (const candidate of [clean, `${clean}.md`, join(clean, 'index.md')]) {
      if (isFile(candidate)) return candidate
    }
    const publicFile = resolve(docs, 'public', path.replace(/^\//, ''))
    if (inside(join(docs, 'public'), publicFile) && isFile(publicFile)) return publicFile
    return undefined
  }

  const files = readdirSync(docs, { recursive: true, encoding: 'utf8' })
    .filter((file) => file.endsWith('.md') && !file.split(sep).some((part) => part.startsWith('.') || part === 'public' || part === 'node_modules'))
    .toSorted()
  const errors: string[] = []
  let checked = 0
  for (const name of files) {
    const source = join(docs, name)
    const current = analyzeFile(source)
    for (const { href, line } of current.links) {
      if (/^(?:[a-z][a-z\d+.-]*:|\/\/)/i.test(href)) continue
      checked++
      const location = `${name.split(sep).join('/')}:${line}`
      const hash = href.indexOf('#')
      let path: string
      let anchor: string
      try {
        path = decodeURIComponent((hash < 0 ? href : href.slice(0, hash)).split('?')[0])
        anchor = hash < 0 ? '' : decodeURIComponent(href.slice(hash + 1))
      } catch {
        errors.push(`${location}: invalid URL encoding in "${href}"`)
        continue
      }
      // Generated by VitePress, not a source/public file. No blanket allowance
      // for /images/: typos and missing assets must fail like other local links.
      const sitePath = base !== '/' && path.startsWith(base) ? '/' + path.slice(base.length) : path
      if (sitePath === '/sitemap.xml' && !anchor) continue
      const target = path ? findTarget(path, source) : source
      if (!target) {
        errors.push(`${location}: broken link "${href}"`)
      } else if (anchor && extname(target) === '.md' && !analyzeFile(target).anchors.has(anchor)) {
        errors.push(`${location}: missing anchor #${anchor} on ${relative(docs, target).split(sep).join('/')}`)
      }
    }
  }
  return { checked, errors }
}

if (import.meta.main) {
  const result = await checkLinks(resolve(import.meta.dirname, '../docs'), process.env.SITE_BASE || '/')
  console.log(`checked ${result.checked} internal Markdown links and images`)
  if (result.errors.length) {
    for (const error of result.errors) console.error(error)
    process.exitCode = 1
  } else console.log('all internal links and anchors OK')
}
